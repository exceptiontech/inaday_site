     */
    public function show($id)
    {

        if (is_numeric($id)) {
            $article = Article::findofail($id);
        }else {
            $article = Article::where('slug',$id)->first();
        }

        $random = Article::all()->random(2);
        
        return view('front.blog.show')->withArticle($article)->withRandom($random);
    }

